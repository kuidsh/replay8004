"""List every AWS resource that belongs to replay8004 (read-only). Used before deploys and for teardown.

  python scripts/aws_inventory.py --profile replay8004-deployer-mfa [--region us-east-1] [--markdown docs/AWS-RESOURCES.md]

Finds resources three ways, so nothing is missed: CloudFormation stacks named replay8004-* (and their physical
resources), anything tagged Project=replay8004, and Secrets Manager secrets named replay8004/*. Prints names and
types only (no account id, no ARNs, no secret values). Random suffixes that AWS adds to generated names (secret
suffixes, CloudFormation stack ids, role/table/bucket suffixes) are replaced with "…", so the file can be published.
The evidence bucket names stay: they are public anyway (every on-chain responseURI contains them).
"""
import argparse
import json
import re
import subprocess
import sys


def aws(profile, region, *args):
    out = subprocess.run(["aws", *args, "--profile", profile, "--region", region, "--output", "json"],
                         capture_output=True, text=True)
    if out.returncode:
        return {"_error": out.stderr.strip().splitlines()[-1][:200]}
    return json.loads(out.stdout or "{}")


def short(arn_or_name: str) -> str:
    """Strip the account id: keep service, region-less resource part."""
    if not arn_or_name.startswith("arn:"):
        return arn_or_name
    parts = arn_or_name.split(":", 5)
    return f"{parts[2]}:{parts[5]}"


def redact(name: str) -> str:
    """Drop AWS-generated random parts; keep the human-chosen prefix. Evidence bucket names are already public."""
    if "evidencebucket-" in name:
        return name
    name = re.sub(r"/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", "/…", name)  # stack id
    name = re.sub(r"(secret:\S+?)-[A-Za-z0-9]{6}$", r"\g<1>-…", name)  # Secrets Manager suffix
    return re.sub(r"-[A-Za-z0-9]{12,13}$", "-…", name)  # CloudFormation physical-id suffix


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", required=True)
    ap.add_argument("--region", default="us-east-1")
    ap.add_argument("--markdown")
    a = ap.parse_args()
    rows, errors = [], []

    stacks = aws(a.profile, a.region, "cloudformation", "list-stacks", "--stack-status-filter",
                 "CREATE_COMPLETE", "UPDATE_COMPLETE", "UPDATE_ROLLBACK_COMPLETE", "ROLLBACK_COMPLETE",
                 "CREATE_FAILED", "ROLLBACK_FAILED", "DELETE_FAILED", "UPDATE_ROLLBACK_FAILED", "IMPORT_COMPLETE")
    if "_error" in stacks:
        errors.append(("stacks", stacks["_error"]))
    names = [s["StackName"] for s in stacks.get("StackSummaries", [])
             if s["StackName"].startswith("replay8004-") or s["StackName"] == "aws-sam-cli-managed-default"]
    for name in sorted(names):
        rows.append(("CloudFormation stack", name, "stack"))
        res = aws(a.profile, a.region, "cloudformation", "list-stack-resources", "--stack-name", name)
        for r in res.get("StackResourceSummaries", []):
            rows.append((r["ResourceType"], r.get("PhysicalResourceId", "?"), f"stack {name}"))

    tagged = aws(a.profile, a.region, "resourcegroupstaggingapi", "get-resources",
                 "--tag-filters", "Key=Project,Values=replay8004")
    if "_error" in tagged:
        errors.append(("tags", tagged["_error"]))
    for t in tagged.get("ResourceTagMappingList", []):
        rows.append(("tagged Project=replay8004", short(t["ResourceARN"]), "tag"))

    secrets = aws(a.profile, a.region, "secretsmanager", "list-secrets", "--filters", "Key=name,Values=replay8004/")
    if "_error" in secrets:
        errors.append(("secrets", secrets["_error"]))
    for s in secrets.get("SecretList", []):
        rows.append(("Secrets Manager secret", s["Name"], "name replay8004/*"))

    rows.append(("IAM user (root removes it last)", "replay8004-deployer", "fixed name"))
    for p in ("replay8004-deployer", "replay8004-deployer-extra", "replay8004-boundary"):
        rows.append(("IAM managed policy (root removes it last)", p, "fixed name"))

    seen, out = set(), []
    for r in rows:
        key = (r[0], r[1])
        if key not in seen:
            seen.add(key)
            out.append(r)
    lines = [f"| {t} | `{redact(n)}` | {how} |" for t, n, how in out]
    table = "| type | name | found by |\n|---|---|---|\n" + "\n".join(lines)
    print(table)
    for where, e in errors:
        print(f"WARNING ({where}): {e}", file=sys.stderr)
    if a.markdown:
        with open(a.markdown, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"# AWS resources ({a.region})\n\nGenerated by `scripts/aws_inventory.py`. Names only; AWS-generated random suffixes shown as `…`.\n\n{table}\n")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
